package in.systemattic.smberp.ejb;

import in.systemattic.smberp.entity.BillOfMaterials;
import in.systemattic.smberp.entity.BomItem;
import in.systemattic.smberp.entity.ManufacturingWorkOrder;
import in.systemattic.smberp.entity.StockLedger;
import in.systemattic.smberp.entity.WorkOrderComponent;
import jakarta.ejb.EJB;
import jakarta.ejb.EJBException;
import jakarta.ejb.Stateless;
import jakarta.ejb.TransactionAttribute;
import jakarta.ejb.TransactionAttributeType;
import jakarta.persistence.EntityManager;
import jakarta.persistence.PersistenceContext;
import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

@Stateless
public class ManufacturingWorkOrderFacade {

    @PersistenceContext(unitName = "smberpPU")
    private EntityManager entityManager;

    @EJB
    private StockLedgerFacade stockLedgerFacade;

    public void create(ManufacturingWorkOrder workOrder) {
        if (workOrder.getWorkOrderNumber() == null || workOrder.getWorkOrderNumber().trim().isEmpty()) {
            String autoGeneratedNumber = "WO-" + System.currentTimeMillis();
            workOrder.setWorkOrderNumber(autoGeneratedNumber);
        }

        if (workOrder.getBom() == null || workOrder.getBom().getId() == null) {
            throw new IllegalArgumentException("A bill of materials is required.");
        }
        if (workOrder.getQuantityTarget() == null) {
            throw new IllegalArgumentException("A target quantity is required.");
        }

        BillOfMaterials activeBom = entityManager.find(
                BillOfMaterials.class, workOrder.getBom().getId());
        if (activeBom == null) {
            throw new IllegalArgumentException("The selected bill of materials does not exist.");
        }

        workOrder.setComponents(new ArrayList<>());
        for (BomItem bomItem : activeBom.getItems()) {
            WorkOrderComponent componentLine = new WorkOrderComponent();
            componentLine.setWorkOrder(workOrder);
            componentLine.setComponentProduct(bomItem.getComponentProduct());
            componentLine.setQuantityRequired(
                    bomItem.getQuantity().multiply(workOrder.getQuantityTarget()));
            componentLine.setQuantityIssued(BigDecimal.ZERO);
            workOrder.getComponents().add(componentLine);
        }
        entityManager.persist(workOrder);
    }

    public void edit(ManufacturingWorkOrder entity) {
        entityManager.merge(entity);
    }

    public void remove(ManufacturingWorkOrder entity) {
        ManufacturingWorkOrder managedEntity = entityManager.merge(entity);
        managedEntity.getComponents().clear();
        entityManager.remove(managedEntity);
    }

    public ManufacturingWorkOrder find(Object id) {
        return entityManager.find(ManufacturingWorkOrder.class, id);
    }

    public List<ManufacturingWorkOrder> findAll() {
        return entityManager.createQuery(
                "SELECT workOrder FROM ManufacturingWorkOrder workOrder "
                        + "JOIN FETCH workOrder.bom "
                        + "JOIN FETCH workOrder.warehouse",
                ManufacturingWorkOrder.class)
                .getResultList();
    }

    @TransactionAttribute(TransactionAttributeType.REQUIRED)
    public void transitionStatus(Integer workOrderId, String newStatus) {
        ManufacturingWorkOrder workOrder = find(workOrderId);
        if (workOrder == null) {
            throw new IllegalArgumentException("The work order does not exist.");
        }

        String currentStatus = workOrder.getStatus();
        if ("IN_PROGRESS".equals(newStatus)) {
            if (!"PLANNED".equals(currentStatus)) {
                throw new IllegalStateException(
                        "Only planned work orders can be started.");
            }
            for (WorkOrderComponent component : workOrder.getComponents()) {
                BigDecimal currentStock = stockLedgerFacade.getStockBalance(
                        component.getComponentProduct().getId(),
                        workOrder.getWarehouse().getId());
                if (currentStock.compareTo(component.getQuantityRequired()) < 0) {
                    throw new EJBException(
                            "Cannot start production. Insufficient stock for: "
                                    + component.getComponentProduct().getName());
                }
            }
            for (WorkOrderComponent component : workOrder.getComponents()) {
                StockLedger ledger = new StockLedger();
                ledger.setProduct(component.getComponentProduct());
                ledger.setWarehouse(workOrder.getWarehouse());
                ledger.setTransactionType("WORK_ORDER_ISSUE");
                ledger.setReferenceId(workOrder.getId());
                ledger.setQuantity(component.getQuantityRequired().negate());
                ledger.setTransactionDate(LocalDateTime.now());
                entityManager.persist(ledger);
            }
            entityManager.flush();
        } else if ("COMPLETED".equals(newStatus)) {
            if (!"IN_PROGRESS".equals(currentStatus)) {
                throw new IllegalStateException(
                        "Only in-progress work orders can be completed.");
            }
        }

        workOrder.setStatus(newStatus);
        entityManager.merge(workOrder);
    }

    public List<ManufacturingWorkOrder> findByStatus(String status) {
        return entityManager.createQuery(
                "SELECT workOrder FROM ManufacturingWorkOrder workOrder "
                        + "WHERE workOrder.status = :status",
                ManufacturingWorkOrder.class)
                .setParameter("status", status)
                .getResultList();
    }
}
